const { spawnSync } = require('child_process');
const run = (args, input) => {
  const r = spawnSync(process.execPath, args, { cwd: __dirname, encoding: 'utf8', argv0: 'node', input });
  console.log(`== ${JSON.stringify(args)}${input === undefined ? '' : ` < ${JSON.stringify(input)}`}: status ${r.status}`);
  process.stdout.write(r.stdout);
  process.stdout.write(r.stderr);
};
run(['-p']);
run(['--print']);
run(['-p', '-1']);
run(['--print', '-1']);
run(['-p', '-foo', '1']);
run(['-p', ' ']);
run(['-p'], '6 * 7');
run(['-p'], 'process.argv.length');
run(['-p', '--no-warnings'], 'process.execArgv');
run(['-p', '-'], '6 * 7');
run(['-p', '-', 'a'], 'process.argv.slice(1)');
run(['-p', '', 'a'], 'process.argv.slice(1)');
run(['-p', '-e', '1 + 2']);
run(['-p', '-p', 'process.execArgv']);
run(['-p', '1', '-e', '2']);
run(['-e', '1', '-p']);
run(['--print', 'process.execArgv']);
run(['--print=1', 'process.execArgv']);
run(['--print='], '8');
run(['--no-print', 'console.log(3)']);
run(['-p', '--', 'script.js', 'a']);
run(['--', 'script.js', 'a', '--', 'b']);
run(['--'], 'console.log(process.argv.length)');
run(['-p', '-e']);
run([''], 'console.log(process.argv.slice(1))');
const { Worker } = require('worker_threads');
const w = new Worker("process.emitWarning('w'); console.log('worker', process.execArgv)", { eval: true, execArgv: ['-p', '--no-warnings'] });
w.on('exit', (code) => console.log('worker exit', code));
